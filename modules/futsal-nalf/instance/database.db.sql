CREATE TABLE IF NOT EXISTS "game_cameras" (
	"id"	INTEGER NOT NULL,
	"game_id"	INTEGER NOT NULL,
	"camera_id"	INTEGER NOT NULL,
	"location"	VARCHAR(200) NOT NULL,
	"is_motorized"	BOOLEAN NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	CONSTRAINT "unique_game_camera" UNIQUE("game_id","camera_id"),
	CONSTRAINT "unique_game_location" UNIQUE("game_id","location"),
	PRIMARY KEY("id"),
	FOREIGN KEY("camera_id") REFERENCES "cameras"("id"),
	FOREIGN KEY("game_id") REFERENCES "games"("id")
