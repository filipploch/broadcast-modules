CREATE TABLE IF NOT EXISTS "game_commentators" (
	"id"	INTEGER NOT NULL,
	"game_id"	INTEGER NOT NULL,
	"commentator_id"	INTEGER NOT NULL,
	"type"	VARCHAR(50) NOT NULL,
