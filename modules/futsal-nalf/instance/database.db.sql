	PRIMARY KEY("id"),
	FOREIGN KEY("season_id") REFERENCES "seasons"("id")
);
CREATE TABLE IF NOT EXISTS "players" (
	"id"	INTEGER NOT NULL,
	"foreign_id"	VARCHAR(500),
	"first_name"	VARCHAR(100) NOT NULL,
	"last_name"	VARCHAR(100) NOT NULL,
	"number"	INTEGER,
	"team_id"	INTEGER NOT NULL,
	"is_goalkeeper"	BOOLEAN NOT NULL,
	"is_captain"	BOOLEAN NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id"),
	FOREIGN KEY("team_id") REFERENCES "teams"("id")
);
CREATE TABLE IF NOT EXISTS "league_teams" (
	"id"	INTEGER NOT NULL,
	"league_id"	INTEGER NOT NULL,
	"team_id"	INTEGER NOT NULL,
	"group_nr"	INTEGER NOT NULL,
	"created_at"	DATETIME,
	CONSTRAINT "uix_league_team" UNIQUE("league_id","team_id"),
	PRIMARY KEY("id"),
	FOREIGN KEY("team_id") REFERENCES "teams"("id"),
	FOREIGN KEY("league_id") REFERENCES "leagues"("id")
);
CREATE TABLE IF NOT EXISTS "games" (
	"id"	INTEGER NOT NULL,
	"foreign_id"	VARCHAR(500),
	"home_team_id"	INTEGER NOT NULL,
	"away_team_id"	INTEGER NOT NULL,
	"home_team_goals"	INTEGER,
	"away_team_goals"	INTEGER,
	"home_team_fouls"	INTEGER NOT NULL,
	"away_team_fouls"	INTEGER NOT NULL,
	"is_home_team_lost_by_wo"	BOOLEAN NOT NULL,
	"is_away_team_lost_by_wo"	BOOLEAN NOT NULL,
	"status"	INTEGER NOT NULL,
	"league_id"	INTEGER NOT NULL,
	"group_nr"	INTEGER NOT NULL,
	"stadium_id"	INTEGER NOT NULL,
	"date"	DATETIME,
	"round"	INTEGER NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id"),
	FOREIGN KEY("stadium_id") REFERENCES "stadiums"("id"),
	FOREIGN KEY("away_team_id") REFERENCES "teams"("id"),
	FOREIGN KEY("league_id") REFERENCES "leagues"("id"),
	FOREIGN KEY("home_team_id") REFERENCES "teams"("id")
