	"foreign_id"	VARCHAR(500),
	"uniform"	TEXT,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id")
);
CREATE TABLE IF NOT EXISTS "stadiums" (
	"id"	INTEGER NOT NULL,
	"name"	VARCHAR(100) NOT NULL,
	"address"	VARCHAR(200) NOT NULL,
	"city"	VARCHAR(50) NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	CONSTRAINT "uix_stadium_name_city" UNIQUE("name","city"),
	PRIMARY KEY("id")
);
CREATE TABLE IF NOT EXISTS "cameras" (
	"id"	INTEGER NOT NULL,
	"name"	VARCHAR(100) NOT NULL,
	"brand"	VARCHAR(50) NOT NULL,
	"model"	VARCHAR(100) NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id")
);
CREATE TABLE IF NOT EXISTS "events" (
	"id"	INTEGER NOT NULL,
	"name"	VARCHAR(100) NOT NULL,
	"short_name"	VARCHAR(50) NOT NULL,
	"is_reported"	BOOLEAN NOT NULL,
	"image_path"	VARCHAR(500),
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id")
);
CREATE TABLE IF NOT EXISTS "referees" (
	"id"	INTEGER NOT NULL,
	"first_name"	VARCHAR(100) NOT NULL,
	"last_name"	VARCHAR(100) NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id")
);
CREATE TABLE IF NOT EXISTS "commentators" (
	"id"	INTEGER NOT NULL,
	"first_name"	VARCHAR(100) NOT NULL,
	"last_name"	VARCHAR(100) NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id")
);
CREATE TABLE IF NOT EXISTS "leagues" (
	"id"	INTEGER NOT NULL,
	"season_id"	INTEGER NOT NULL,
	"name"	VARCHAR(50) NOT NULL,
	"foreign_id"	VARCHAR(500),
	"games_url"	VARCHAR(500) NOT NULL,
	"table_url"	VARCHAR(500),
