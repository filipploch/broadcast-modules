CREATE TABLE IF NOT EXISTS "settings" (
	"id"	INTEGER NOT NULL,
	"current_season_id"	INTEGER,
	"current_game_id"	INTEGER,
	"current_period_id"	INTEGER,
	"current_timers"	TEXT,
