	"updated_at"	DATETIME,
	CONSTRAINT "unique_game_period_order" UNIQUE("game_id","period_order"),
	PRIMARY KEY("id"),
	FOREIGN KEY("game_id") REFERENCES "games"("id")
);
CREATE TABLE IF NOT EXISTS "penalties" (
	"id"	INTEGER NOT NULL,
	"game_id"	INTEGER NOT NULL,
	"home_team_penalties"	INTEGER NOT NULL,
	"away_team_penalties"	INTEGER NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	PRIMARY KEY("id"),
	FOREIGN KEY("game_id") REFERENCES "games"("id")
);
CREATE TABLE IF NOT EXISTS "player_games" (
	"id"	INTEGER NOT NULL,
	"player_id"	INTEGER NOT NULL,
	"game_id"	INTEGER NOT NULL,
	"team_id"	INTEGER NOT NULL,
	"is_goalkeeper"	BOOLEAN NOT NULL,
	"is_captain"	BOOLEAN NOT NULL,
	"number"	INTEGER,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	CONSTRAINT "unique_player_game" UNIQUE("player_id","game_id"),
	PRIMARY KEY("id"),
	FOREIGN KEY("player_id") REFERENCES "players"("id"),
	FOREIGN KEY("team_id") REFERENCES "teams"("id"),
	FOREIGN KEY("game_id") REFERENCES "games"("id")
);
CREATE TABLE IF NOT EXISTS "game_referees" (
	"id"	INTEGER NOT NULL,
	"game_id"	INTEGER NOT NULL,
	"referee_id"	INTEGER NOT NULL,
	"type"	VARCHAR(50) NOT NULL,
	"created_at"	DATETIME,
	"updated_at"	DATETIME,
	CONSTRAINT "unique_game_referee" UNIQUE("game_id","referee_id"),
	PRIMARY KEY("id"),
	FOREIGN KEY("game_id") REFERENCES "games"("id"),
	FOREIGN KEY("referee_id") REFERENCES "referees"("id")
